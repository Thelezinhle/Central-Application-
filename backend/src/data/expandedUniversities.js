// Function to get universities by country
export const getUniversitiesByCountry = (country) => {
    return REAL_UNIVERSITIES.filter(uni => 
        uni.country.toLowerCase().includes(country.toLowerCase())
    );
};

// Function to search universities
export const searchUniversities = (query) => {
    const q = query.toLowerCase();
    return REAL_UNIVERSITIES.filter(uni =>
        uni.name.toLowerCase().includes(q) ||
        uni.country.toLowerCase().includes(q) ||
        (uni.id && uni.id.toLowerCase().includes(q))
    );
};

